#!/usr/bin/env python3
"""Emit kernels3d/bindings.glsli from the one binding table in material/Bindings.gd.

`--check` regenerates and diffs against the checked-in include; non-zero when stale.
"""
import argparse
import os
import sys

# The generator must not dirty the tree it generates into: importing lib_bindings writes __pycache__.
sys.dont_write_bytecode = True

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_bindings as LB

BANNER = "// GENERATED by scripts/gen_bindings.py from material/Bindings.gd. Edit the table, regenerate."


def glsli_text():
    rows = LB.slots()
    width = max(len(n) for n, _b in rows) + len("LA_BIND_")
    lines = [BANNER, "", "#ifndef LA_BINDINGS_GLSLI", "#define LA_BINDINGS_GLSLI", ""]
    for name, binding in rows:
        lines.append("#define %-*s %d" % (width, "LA_BIND_" + name.upper(), binding))
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    try:
        want = glsli_text()
    except (LB.Missing, OSError) as err:
        print("gen_bindings: %s" % err, file=sys.stderr)
        return 2
    rel = os.path.relpath(LB.GLSLI_OUT, LB.ROOT)
    if args.check:
        have = open(LB.GLSLI_OUT, encoding="utf-8").read() if os.path.isfile(LB.GLSLI_OUT) else None
        if have != want:
            print("STALE %s — regenerate with scripts/gen_bindings.py" % rel, file=sys.stderr)
            return 1
        return 0
    with open(LB.GLSLI_OUT, "w", encoding="utf-8") as fh:
        fh.write(want)
    print("wrote %s" % rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
